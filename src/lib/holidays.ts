/** その日の祝日名。祝日でなければ null */
export function holidayOf(year: number, month: number, day: number): string | null {
  return HOLIDAYS[year]?.[`${month}-${day}`] ?? null;
}

/** 祝日表を持っている年か。持っていない年は一括反映で祝日が付かない */
export function hasHolidayTable(year: number): boolean {
  return year in HOLIDAYS;
}

/**
 * 表はあるが、官報でまだ確定していない年か（＝ 計算による予測）。
 *
 * 🔴 表が無い年は false を返す。そちらは `hasHolidayTable()` の担当。
 *    「表が無い」と「予測」は別の状態で、出す警告の重さも違う（C-5）。
 */
export function isPredictedYear(year: number): boolean {
  return hasHolidayTable(year) && year > CONFIRMED_THROUGH;
}

/** テストと生成スクリプトの突き合わせ用。表に載っている年の一覧 */
export function tabledYears(): number[] {
  return Object.keys(HOLIDAYS)
    .map(Number)
    .sort((a, b) => a - b);
}
