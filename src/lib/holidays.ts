// ライブラリを使わず表に持つ。外部の読み込みが増えず、目で確かめられる。
//
//   2024〜2027 … 🟢 官報（暦要項）で確定ずみ。警告を出さない
//   2028〜2035 … ℹ️ 計算による予測。C-5 が「予測です」と出す
//   2036〜     … ⚠️ 表なし。C-5 が「表がありません」と出す
//
// 🔴 表は手で書かない。祝日法のルールから生成する（`scripts/gen-holidays.mjs`）。
//    生成したら、**2026年で答え合わせをしてから**貼る。
//    2026年は 2026-08-05 から使っていて、正しいと分かっている年だから。
//    貼ったあとは `holidays.test.ts` が、表とルールが合っているかを毎回確かめる。
//
// -------------------------------------------------------------------
// 🔴 なぜ「確定」と「予測」を分けるのか（2026-08-08 に検討し、同じ日に実装）
//
// 先まで足せない理由はコードではなく、**どこまでを「正しい」と言えるか**にあった。
//
//   元日・建国記念の日 など日付が固定  … 何十年先でも確実（法律に日付が書いてある）
//   成人の日・海の日 など「第2月曜」型 … 確実（曜日の並びで決まる）
//   振替休日・国民の休日               … 上が決まれば自動で決まる
//   🔴 春分の日・秋分の日              … **翌年ぶんまでしか確定しない**
//
// 🔴 春分・秋分だけは、法律に日付が書かれていない。
//    天文の計算で決まり、**国立天文台が前の年の2月に官報で公告して確定する**（暦要項）。
//    計算値は何十年先まで出せてまず外れないが、**「予測」であって「確定」ではない。**
//    （2027年ぶんは 2026-02-02 に公告された。3/21・9/23 で、計算値と一致していた）
//
// 🔴 そして祝日は法改正で動く。予測が外れる本当の原因はこちら。
//      2016年 山の日ができた
//      2020年 体育の日が「スポーツの日」に変わった
//      2020年 天皇誕生日が 12/23 → 2/23 に動いた（🔴 次の代替わりでも動く）
//      2020・2021年 オリンピックのために祝日を移した
//
// 🔴 いちばん大事なこと。**間違った表は、警告を消す。**
//
//      表が無い年     → C-5 が ⚠️「表がありません」 → 気づける
//      確定している年 → 正しく動く
//      予測の年       → C-5 が ℹ️「予測です」       → 気づける
//
//    先まで埋めるというのは、この安全網を先まで外すということ。
//    **だから「予測」の段を作った。黙って間違える年を1つも作らないため。**
//
// 📌 2035年で止めた理由。**計算の限界ではなく、法改正の確からしさ。**
//    近似式は2099年まで使えるが、10年より先は「予測」と呼ぶことすら怪しくなる。
//    （天皇誕生日は代替わりで動く。それがいつかは誰にも分からない）
//
// 📌 1年に1回やること（2月。国立天文台が翌年の暦要項を公告したあと）
//      ① 公告された年の春分・秋分が、下の表と合っているか確かめる
//      ② 合っていたら CONFIRMED_THROUGH を1つ進める
//      ③ 合っていなければ、その年の表を直す
//    さらに先を足したいときは `node scripts/gen-holidays.mjs 2036 2045`。
// ===================================================================

