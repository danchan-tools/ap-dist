/**
 * 入力欄の文字を「0以上の整数」にする。**読めなければ `null`。**
 *
 * 🔴 `null` を 0 に落とさないこと。
 *    呼ぶ側が `?? 0` と書いた瞬間に、この関数を作った意味が消える。
 *    「読めなかった」ことは、利用者に伝えて入れ直してもらう。
 *
 * | 入れたもの | 返るもの | なぜ |
 * |---|---|---|
 * | `"4285"` | `4285` | ふつうの入力 |
 * | `"4,285"` | `4285` | **契約書からの転記でカンマは普通に付く** |
 * | `"4，285"` | `4285` | 全角カンマ（日本語入力のまま打つと出る） |
 * | `" 4285 "` | `4285` | 前後の空白は落とす |
 * | `""` | `null` | 空欄。呼ぶ側が「未入力」か「0」かを決める |
 * | `"あ"` `"1e5"` `"0x10"` | `null` | 読めない |
 * | `"-1"` `"1.5"` | `null` | 0以上の整数だけを受け付ける |
 */
export function parseAmount(s: string): number | null {
  // 半角・全角のカンマと読点を落とす。区切り文字として打たれるのは、この3つ
  const t = s.replace(/[,，、]/g, "").trim();
  if (t === "") return null;
  // 🔴 `Number()` に任せない。"1e5" が 100000、"0x10" が 16、" " が 0 になる
  if (!/^\d+$/.test(t)) return null;
  const n = Number(t);
  return Number.isSafeInteger(n) ? n : null;
}

/**
 * 単価の欄。**空欄は 0**（まだ入れていない）として扱う。読めない文字は `null`。
 *
 * 📌 単価は「0＝未入力」で表す決めごと（DBの既定値も 0）。
 *    契約時間の下限・上限が「null＝未入力」なのと逆なので注意（08 §3.3 ②）。
 */
export function parseMoneyField(s: string): number | null {
  return s.trim() === "" ? 0 : parseAmount(s);
}
